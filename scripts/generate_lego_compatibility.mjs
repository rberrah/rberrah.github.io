import assert from 'node:assert/strict';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { parseModelCode } from '../src/lib/lego/mlxtran.js';
import { exportPmetrics } from '../src/lib/lego/pmetrics.js';
import { suppliedModels, externalModels } from './fixtures/lego-imports.mjs';

const root = new URL('../', import.meta.url);
const formats = ['mrgsolve', 'mlxtran', 'nonmem', 'pmetrics'];
const spec = { version: 3, nodes: [{ id: 1, kind: 'central', name: 'CENT', dose: 100, vol: 30 }],
  edges: [{ id: 1, from: 1, to: 'OUT', kinetics: 'first_order', k: 0.2 }], covariates: [] };
const encoded = encodeURIComponent(JSON.stringify(spec));
const pmetrics = exportPmetrics({ spec, parameters: [{ name: 'v_CENT', value: 30 }, { name: 'k_CENT_e', value: 0.2 }],
  secondary: [], equations: { CENT: '-k_CENT_e*CENT' }, observed: 'CENT' }).code;
const multipleAdministrationOutput = `[LONGITUDINAL]
input = {KA, CL, V, K12, K21, V2}
PK:
depot(target=DEPOT, adm=1)
depot(target=CENT, adm=2, Tk0=2)
EQUATION:
ddt_DEPOT = -KA*DEPOT
ddt_CENT = KA*DEPOT - (CL/V)*CENT - K12*CENT + K21*PERI
ddt_PERI = K12*CENT - K21*PERI
Ccentral = CENT/V
Cperiph = PERI/V2
Ctotal = Ccentral + Cperiph
OUTPUT:
output = {Ctotal}
table = {Ccentral, Cperiph, Ctotal}`;
const boundedCombined = parseModelCode(multipleAdministrationOutput, 'mlxtran').spec;
assert.deepEqual(boundedCombined.administrations.map((administration) => administration.id), ['1', '2']);
assert.equal(boundedCombined.outputs.find((output) => output.name === 'Ctotal')?.terms.length, 2);
const cases = [
  { id: 'embedded-mrgsolve', sourceFormat: 'mrgsolve', code: `// PK_LEGO_SPEC_V1:${encoded}\n$ODE` },
  { id: 'embedded-mlxtran', sourceFormat: 'mlxtran', code: `; PK_LEGO_SPEC_V1:${encoded}\n[LONGITUDINAL]` },
  { id: 'embedded-nonmem', sourceFormat: 'nonmem', code: `; PK_LEGO_SPEC_V1:${encoded}\n$PROBLEM` },
  { id: 'embedded-pmetrics', sourceFormat: 'pmetrics', code: pmetrics },
  { id: 'mlxtran-multiple-administrations-output', sourceFormat: 'mlxtran', code: multipleAdministrationOutput },
  ...suppliedModels.map((model) => ({ id: model.id, sourceFormat: 'mlxtran', code: model.code })),
  ...externalModels.map((model) => ({ id: model.id, sourceFormat: model.format, code: model.code }))
];
for (const file of readdirSync(new URL('static/tdm/models/', root)).filter((name) => name.endsWith('.cpp')).sort()) {
  cases.push({ id: file.replace(/\.cpp$/, ''), sourceFormat: 'mrgsolve', code: readFileSync(new URL(`static/tdm/models/${file}`, root), 'utf8') });
}

const rows = [];
for (const item of cases) for (const format of formats) {
  try {
    const parsed = parseModelCode(item.code, format);
    const status = parsed.mode === 'exact' ? 'exact' : 'structural only';
    rows.push({ model: item.id, sourceFormat: item.sourceFormat, testedAs: format, status,
      reason: status === 'exact' ? 'embedded versioned Lego specification' : (parsed.warnings?.map((warning) => warning.code).join(', ') || 'bounded structural reconstruction') });
  } catch (error) {
    rows.push({ model: item.id, sourceFormat: item.sourceFormat, testedAs: format, status: 'rejected',
      reason: String(error.detail || error.code || error.message || 'unsupported structure').replace(/\s+/g, ' ').slice(0, 240) });
  }
}

assert(rows.every((row) => ['exact', 'structural only', 'rejected'].includes(row.status)));
assert(rows.some((row) => row.testedAs === 'pmetrics' && row.status === 'exact'));
const report = { version: 1, generatedFromTests: true, cases: cases.length, checks: rows.length, rows };
const json = `${JSON.stringify(report, null, 2)}\n`;
const counts = Object.fromEntries(['exact', 'structural only', 'rejected'].map((status) => [status, rows.filter((row) => row.status === status).length]));
const markdown = `# Lego translator compatibility matrix\n\n> Generated by \`scripts/generate_lego_compatibility.mjs\`; do not edit manually.\n\n` +
  `The matrix contains ${rows.length} parser checks over ${cases.length} examples and library models. ` +
  `It reports ${counts.exact} exact restores, ${counts['structural only']} structural reconstructions and ${counts.rejected} explicit rejections. ` +
  `A parser check is not native NONMEM or Monolix validation.\n\n` +
  `| Model/example | Source | Parser | Result | Reason |\n| --- | --- | --- | --- | --- |\n` +
  rows.map((row) => `| \`${row.model}\` | ${row.sourceFormat} | ${row.testedAs} | ${row.status} | ${row.reason.replace(/\|/g, '\\|')} |`).join('\n') + '\n';

const outputs = [['docs/lego-compatibility.json', json], ['docs/lego-compatibility.md', markdown]];
if (process.argv.includes('--check')) {
  for (const [file, content] of outputs) assert.equal(readFileSync(new URL(file, root), 'utf8').replace(/\r/g, ''), content, `${file} is stale`);
  console.log(`Lego compatibility matrix is current: ${rows.length} checks.`);
} else {
  for (const [file, content] of outputs) writeFileSync(new URL(file, root), content, 'utf8');
  console.log(`Generated Lego compatibility matrix: ${rows.length} checks.`);
}

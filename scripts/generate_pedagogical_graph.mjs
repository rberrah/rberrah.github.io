import assert from 'node:assert/strict';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import matter from 'gray-matter';
import { exercises } from '../src/lib/content/exercises.js';
import { guidedActivities } from '../src/lib/content/guidedActivities.js';
import { beginnerTrack, tracks } from '../src/lib/content/tracks.js';

const root = new URL('../', import.meta.url);
const directory = new URL('src/content/chapters/', root);
const chapters = readdirSync(directory).filter((file) => file.endsWith('.md') && !file.startsWith('_')).sort().map((file) => {
  const raw = readFileSync(new URL(file, directory), 'utf8');
  return { raw, ...matter(raw).data };
});
const trackDefinitions = [beginnerTrack, ...tracks];
const slugs = new Set(chapters.map((chapter) => chapter.slug));
const nodes = [], edges = [];
for (const track of trackDefinitions) {
  nodes.push({ id: `track:${track.id}`, type: 'track', label: track.i18n.fr.title });
}
for (const chapter of chapters) {
  nodes.push({ id: `chapter:${chapter.slug}`, type: 'chapter', label: chapter.title, track: chapter.track });
  for (const prerequisite of chapter.prerequisites ?? []) edges.push({ from: `chapter:${prerequisite}`, to: `chapter:${chapter.slug}`, type: 'prerequisite' });
  for (const term of chapter.glossary ?? []) {
    nodes.push({ id: `glossary:${term}`, type: 'definition', label: term });
    edges.push({ from: `chapter:${chapter.slug}`, to: `glossary:${term}`, type: 'defines' });
  }
  for (const match of chapter.raw.matchAll(/\bviz="([^"]+)"/g)) {
    nodes.push({ id: `visualization:${match[1]}`, type: 'visualization', label: match[1] });
    edges.push({ from: `chapter:${chapter.slug}`, to: `visualization:${match[1]}`, type: 'illustrates' });
  }
}
for (const [index, exercise] of exercises.entries()) {
  nodes.push({ id: `exercise:short-${index}`, type: 'exercise', label: exercise.q });
  edges.push({ from: `chapter:${exercise.chapter}`, to: `exercise:short-${index}`, type: 'practises' });
}
for (const activity of guidedActivities) {
  nodes.push({ id: `activity:${activity.id}`, type: activity.kind === 'synthesis' ? 'synthesis' : 'guided-activity', label: activity.title?.fr ?? activity.id });
  if (activity.chapter) edges.push({ from: `chapter:${activity.chapter}`, to: `activity:${activity.id}`, type: 'practises' });
  if (activity.track) edges.push({ from: `track:${activity.track}`, to: `activity:${activity.id}`, type: 'integrates' });
}
const compare = (left, right) => left < right ? -1 : left > right ? 1 : 0;
const uniqueNodes = [...new Map(nodes.map((node) => [node.id, node])).values()]
  .sort((left, right) => compare(left.id, right.id));
edges.sort((left, right) => compare(left.from, right.from) || compare(left.to, right.to) || compare(left.type, right.type));
const nodeIds = new Set(uniqueNodes.map((node) => node.id));
assert(edges.every((edge) => nodeIds.has(edge.from) && nodeIds.has(edge.to)), 'Graph edge references an unknown node');
assert(edges.filter((edge) => edge.from.startsWith('chapter:')).every((edge) => slugs.has(edge.from.slice(8))), 'Graph contains an unknown chapter source');
const chapterEdges = (slug, types) => edges.filter((edge) => edge.from === `chapter:${slug}` && types.includes(edge.type));
const debt = {
  orphanChapters: chapters.filter((chapter) => !chapterEdges(chapter.slug, ['defines', 'illustrates', 'practises']).length).map((chapter) => chapter.slug),
  chaptersWithoutDefinition: chapters.filter((chapter) => !(chapter.glossary?.length)).map((chapter) => chapter.slug),
  chaptersWithoutExercise: chapters.filter((chapter) => !chapterEdges(chapter.slug, ['practises']).length).map((chapter) => chapter.slug),
  chaptersWithoutVisualization: chapters.filter((chapter) => !chapterEdges(chapter.slug, ['illustrates']).length).map((chapter) => chapter.slug)
};
const graph = { version: 1, nodes: uniqueNodes, edges, debt };
const json = `${JSON.stringify(graph, null, 2)}\n`;
const markdown = `# PMx Explain pedagogical graph\n\n> Generated by \`scripts/generate_pedagogical_graph.mjs\`; do not edit manually.\n\n` +
  `The graph links ${chapters.length} chapters and ${trackDefinitions.length} tracks to definitions, visualizations, exercises, guided activities and synthesis cases. ` +
  `Every edge resolves to a generated node. Detection is structural and does not certify pedagogical relevance.\n\n` +
  `| Detected debt | Count | Items |\n| --- | ---: | --- |\n` +
  Object.entries(debt).map(([key, values]) => `| ${key} | ${values.length} | ${values.join(', ') || 'None'} |`).join('\n') + '\n';
const outputs = [['docs/pedagogical-graph.json', json], ['docs/pedagogical-graph.md', markdown]];
if (process.argv.includes('--check')) {
  for (const [file, content] of outputs) assert.equal(readFileSync(new URL(file, root), 'utf8').replace(/\r/g, ''), content, `${file} is stale`);
  console.log(`Pedagogical graph is current: ${uniqueNodes.length} nodes, ${edges.length} edges.`);
} else {
  for (const [file, content] of outputs) writeFileSync(new URL(file, root), content, 'utf8');
  console.log(`Generated pedagogical graph: ${uniqueNodes.length} nodes, ${edges.length} edges.`);
}
